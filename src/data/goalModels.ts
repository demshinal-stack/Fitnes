/**
 * Ожидаемые изменения тела от силовых тренировок по данным исследований.
 * Эффект копится с каждой тренировкой, где есть упражнения цели, и замедляется со временем:
 * E(n) = max · (1 − e^(−n/tau)), где n — число таких тренировок.
 * Коэффициенты подобраны так, чтобы на дозе из исследований (обычно 24–36 тренировок за 8–12 недель)
 * получалось среднее, которое они сообщают. Это ориентир, а не обещание: разброс между людьми примерно в 2 раза.
 */
export interface GoalModel {
  /** Что меряем: «обхват ягодиц» */
  metric: string
  unit: 'см' | '°' | '%'
  /** 1 — прибавка (+), −1 — убавка (−) */
  sign: 1 | -1
  /** Предел за первый год только от силовых */
  max: number
  /** Сколько тренировок до ~63% предела */
  tau: number
  /** Множитель, если ещё следить за питанием и шагами */
  boost?: number
  boostLabel?: string
  defaultTarget: number
  /** Шаг для выбора цели */
  step: number
  /** Как мерить самой */
  howToMeasure: string
  evidence: string
  sources: { title: string; url: string }[]
}

